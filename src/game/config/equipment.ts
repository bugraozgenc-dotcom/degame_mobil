export const upgradeCost = (t: EquipmentType) => Math.round(EQUIPMENT[t].cost * 0.5);

export const levelMult = (lvl: 1 | 2) => (lvl === 2 ? 1.25 : 1);

export const isCameraLike = (t: EquipmentType) =>
  t === 'fixedCam' || t === 'bulletCam' || t === 'ptzCam' || t === 'thermalCam' || t === 'tower' || t === 'drone' || t === 'mik' || t === 'mas' || t === 'mia';

export const BONUS_TYPES: EquipmentType[] = ['mik', 'mas', 'mia'];

export const deviceValue = (t: EquipmentType, lvl: 1 | 2) =>
  EQUIPMENT[t].cost + (lvl === 2 ? upgradeCost(t) : 0);
